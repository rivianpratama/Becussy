def fig_perlang(tag: str = "v4-360-single") -> None:
    passes = by_lang_passes(tag)
    core_pts, ext_pts, ticks, names = [], [], [], []
    for i, lang in enumerate(LANG_ORDER):
        v = passes.get(lang, [])
        if not v:
            continue
        n, k = len(v), sum(v)
        lo, hi = wilson(k, n)
        acc = k / n * 100
        entry = f"({i},{acc}) += (0,{hi * 100 - acc}) -= (0,{acc - lo * 100})"
        (core_pts if lang in CORE_LANGS else ext_pts).append(entry)
        ticks.append(str(i))
        names.append(lang)
    body = f"""\\begin{{figure}}[t]
\\centering
\\begin{{tikzpicture}}
\\begin{{axis}}[
  width=\\columnwidth, height=4.8cm,
  ybar, ymin=0, ymax=105,
  ylabel={{Accuracy (\\%)}},
  xtick={{{','.join(ticks)}}}, xticklabels={{{','.join(names)}}},
  x tick label style={{font=\\scriptsize\\ttfamily}}, y tick label style={{font=\\scriptsize}},
  label style={{font=\\small}},
  bar width=7pt, enlarge x limits={{abs=0.7}},
  error bars/y dir=both, error bars/y explicit,
  legend style={{font=\\scriptsize, at={{(0.98,0.97)}}, anchor=north east, draw=none,
    fill=none, legend columns=1}},
]
\\addplot[fill=black!55, draw=black] coordinates {{{' '.join(core_pts)}}};
\\addlegendentry{{core (in corpus)}}
\\addplot[fill=black!12, draw=black] coordinates {{{' '.join(ext_pts)}}};
\\addlegendentry{{extended (unseen)}}
\\end{{axis}}
\\end{{tikzpicture}}
\\caption{{Becussy One per language, Wilson 95\\% intervals. The two core languages are the
only ones in the training corpus. Transfer reaches Spanish, German, French and a trace of
Japanese, then stops dead: Portuguese, Russian, Arabic, Chinese, Korean and Hindi are
exactly zero. Extended $n$ is 6--7 per language, so the intervals are wide by
construction.}}
\\label{{fig:perlang}}
\\end{{figure}}
"""
    write(FIGS / "fig_perlang.tex", f"eval/generations/ag1-{tag}.jsonl (regraded)", body)


def fig_cost(cis: dict[str, tuple[float, float, float]]) -> None:
    """Score and cost as two aligned panels sharing one axis of model names.

    An earlier version plotted score against cost as a labelled scatter. It failed as a
    graph: every API model sits in a 4--8% score band, so the inline names collided into an
    illegible cluster no matter how the anchors were arranged. Splitting the two quantities
    into panels that share a categorical axis removes the collision entirely, and reading
    across a row is a more direct comparison than eyeballing position in a plane.

    The encodings differ on purpose. Score is a bar because it is linear from a meaningful
    zero. Cost is a marker because the axis is logarithmic, where bar length measured from
    an arbitrary left edge would encode nothing.
    """
    data = {d["tag"]: d for d in json.loads((CHARTS / "ag1_cost.json").read_text(encoding="utf-8"))}
    rows = [(t, lb) for t, lb in MODELS if t in data]  # Mercury 2 has no cost datum

    names, score_pts, cost_pts = [], [], []
    for i, (tag, label) in enumerate(reversed(rows)):
        pt, lo, hi = cis[tag]
        plain = label.replace(r"\textbf{", "").replace("}", "").replace(" (ours)", "")
        names.append(plain)
        score_pts.append(f"({pt},{i}) += ({hi - pt},0) -= ({pt - lo},0)")
        cost_pts.append(f"({data[tag]['cost']},{i})")
    ticks = ",".join(str(i) for i in range(len(rows)))

    body = f"""\\begin{{figure*}}[t]
\\centering
\\begin{{tikzpicture}}
\\begin{{groupplot}}[
  group style={{group size=2 by 1, horizontal sep=0.9cm, yticklabels at=edge left}},
  width=0.40\\textwidth, height=5.6cm,
  ytick={{{ticks}}}, yticklabels={{{','.join(names)}}},
  ytick style={{draw=none}}, enlarge y limits={{abs=0.6}},
  y tick label style={{font=\\scriptsize}}, x tick label style={{font=\\scriptsize}},
  label style={{font=\\small}},
]
\\nextgroupplot[
  xbar, xmin=0, xmax=100, bar width=4.4pt,
  xlabel={{AG1 composite (\\%)}}, xtick={{0,25,50,75,100}},
  error bars/x dir=both, error bars/x explicit,
  title={{\\small(a) What you get}}, title style={{yshift=-1mm}},
]
\\addplot[fill=black!12, draw=black] coordinates {{{' '.join(score_pts)}}};
\\nextgroupplot[
  xmode=log, xmin=0.003, xmax=3,
  xlabel={{Cost of one 135-item run (USD)}},
  xtick={{0.01,0.1,1}}, xticklabels={{0.01,0.10,1.00}},
  % Horizontal rules at each row let the eye track from the shared name axis across to
  % the marker. A stem from the left edge would read as a magnitude, which on a log axis
  % it is not.
  xmajorgrids, ymajorgrids, grid style={{black!10}},
  title={{\\small(b) What it costs}}, title style={{yshift=-1mm}},
]
\\addplot[only marks, mark=*, mark size=1.8pt] coordinates {{{' '.join(cost_pts)}}};
\\end{{groupplot}}
\\end{{tikzpicture}}
\\caption{{The same nine models in the same order, by score (a) and by the cost of
producing it (b). Reading across the top row: the local run scores $11.7\\times$ the best
API result for $1/300$th of the outlay. Bars in (a) carry the bootstrap 95\\% intervals of
Fig.~\\ref{{fig:bars}}; (b) is a log axis, so cost is marked as a position rather than a bar
length. The local cost assumes 160\\,W board power at 25\\,tok/s and \\$0.15/kWh --- an
estimate, not a wattmeter reading --- and API token counts are estimated as characters/4
because \\texttt{{run\\_api.py}} did not persist usage. Mercury~2 is absent from the cost
artifact and so from this figure; it is the lowest scorer in
Table~\\ref{{tab:ag1-main}}.}}
\\label{{fig:cost}}
\\end{{figure*}}
"""
    write(FIGS / "fig_cost.tex", "eval/reports/charts/ag1_cost.json + regraded bootstrap", body)


# ------------------------------------------------------------------------------- main


def main() -> None:
    rows = {r["tag"]: r for r in read_csv(REPS / "hongbai_ag1.csv")}
    missing = [t for t, _ in MODELS if t not in rows]
    if missing:
        raise SystemExit(f"hongbai_ag1.csv is missing rows for: {', '.join(missing)}")

    print("bootstrapping composites (5,000 replicates x 10 models)...")
    cis = {}
    for tag, label in MODELS:
        cis[tag] = bootstrap(by_lang_passes(tag))
        pt, lo, hi = cis[tag]
        csv_score = float(rows[tag]["ag1_score"]) * 100
        flag = "" if abs(pt - csv_score) < 0.15 else f"  <-- CSV says {csv_score:.1f}"
        print(f"  {tag:32s} {pt:5.1f}  [{lo:5.1f}, {hi:5.1f}]{flag}")

    print("tables:")
    tab_ag1_main(rows, cis)
    tab_clauses(rows)
    tab_perlang()
    tab_sweep()
    tab_capability()
    tab_dataset()
    tab_diversity()
    tab_truncation()
    tab_transcripts()

    print("figures:")
    fig_loss()
    fig_ag1_bars(cis)
    fig_perlang()
    fig_cost(cis)

    print("done.")


if __name__ == "__main__":
    main()
