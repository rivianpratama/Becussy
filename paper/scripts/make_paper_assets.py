def tab_perlang(tag: str = "v4-360-single") -> None:
    passes, _, cut = by_lang_split(tag)
    body = [
        r"\begin{table}[t]",
        r"\centering",
        r"\caption{Becussy One per language, Wilson 95\% intervals. The two core languages",
        r"are the only ones in the training corpus. \emph{Cut} counts answers the 220-token",
        r"generation cap truncated mid-sentence; all of them are scored as failures, and the",
        r"cap falls hardest on the scripts the tokenizer handles least efficiently. Hindi is",
        r"truncated on 6 of 6 items, so its $0.0$ measures the token budget and not the",
        r"model; Chinese is truncated on none, so its $0.0$ is real.}",
        r"\label{tab:perlang}",
        r"\small",
        r"\begin{tabular}{llrrrc}",
        r"\toprule",
        r"Lang & Group & $n$ & Cut & Acc.\ (\%) & Wilson 95\% \\",
        r"\midrule",
    ]
    for lang in LANG_ORDER:
        v = passes.get(lang, [])
        if not v:
            continue
        n, k = len(v), sum(v)
        lo, hi = wilson(k, n)
        group = "core" if lang in CORE_LANGS else "ext."
        if lang == "es":
            body.append(r"\midrule")
        body.append(
            f"\\texttt{{{lang}}} & {group} & {n} & {cut.get(lang, 0)} & {k / n * 100:.1f} & "
            f"[{lo * 100:.0f}, {hi * 100:.0f}] \\\\"
        )
    body += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    write(TABLES / "tab_perlang.tex", f"eval/generations/ag1-{tag}.jsonl (regraded)", "\n".join(body))


def tab_truncation() -> None:
    """Sensitivity of the headline to the generation cap.

    Not in any pre-existing report: found while writing the paper. 21 of 135 answers stop
    mid-sentence, and every one of them fails. The scores therefore sit below what the
    model produces when allowed to finish, and the gap is worth naming rather than
    absorbing.
    """
    body = [
        r"\begin{table}[t]",
        r"\centering",
        r"\caption{The reported scores are a lower bound set partly by the token budget.",
        r"Answers cut off by the 220-token cap cannot contain a complete argument, so all of",
        r"them fail; excluding them raises every figure. We report the capped numbers as the",
        r"headline because the cap is part of the harness, but a reader comparing against a",
        r"model with a larger budget should use the second row.}",
        r"\label{tab:truncation}",
        r"\small",
        r"\begin{tabular}{llccc}",
        r"\toprule",
        r"Model & Items & AG1 & Core & Ext. \\",
        r"\midrule",
    ]
    for tag, label in (("v4-360-single", "Becussy One"), ("v3-360-single", "v3 @ 360")):
        allp, keep, cut = by_lang_split(tag)
        n_all = sum(len(v) for v in allp.values())
        n_cut = sum(cut.values())
        a, ac, ae = composite(allp), _macro(allp, CORE_LANGS), _macro(allp, EXTENDED_LANGS)
        k, kc, ke = composite(keep), _macro(keep, CORE_LANGS), _macro(keep, EXTENDED_LANGS)
        body += [
            f"{label} & all {n_all} & {a * 100:.1f} & {ac * 100:.1f} & {ae * 100:.1f} \\\\",
            f"\\quad excl.\\ truncated & {n_all - n_cut} & {k * 100:.1f} & {kc * 100:.1f} & "
            f"{ke * 100:.1f} \\\\",
        ]
        if tag == "v4-360-single":
            body.append(r"\midrule")
    body += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    write(TABLES / "tab_truncation.tex", "eval/generations/ (regraded, split on truncation)", "\n".join(body))


