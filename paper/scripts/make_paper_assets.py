"""Generate every data-derived table and figure in the paper from the repo's own artifacts.

No measurement is typed by hand here. Each writer names its source file, and the numbers
are read (or recomputed with the same code the eval uses) at build time, so a table can
never drift from the CSV it came from. Run it from anywhere:

    python paper/scripts/make_paper_assets.py

Outputs `.tex` fragments into `paper/tables/` and `paper/figs/`, which `main.tex`
`\\input`s. Figures are pgfplots, not raster: the existing PNGs under
`eval/reports/charts/` are HTML screenshots styled for a web page, and this machine's
matplotlib is broken anyway (numpy ABI mismatch).

Two things are deliberately NOT generated here and live as literals in `main.tex`:
the training-configuration table and the Turing-constraint list. Those come from
`training/config.yaml` plus lines in `outputs/train_v3.log`, and the log is gitignored,
so a reader without `outputs/` must still be able to build the paper. Every such literal
carries a source comment in `main.tex`.

Per-language pass counts and bootstrap intervals are recomputed from the raw generations
via `common.hongbai.score_item` rather than parsed out of the rounded markdown reports,
so Wilson bars are exact.
"""

