def write(path: Path, src: str, body: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(HEADER.format(src=src) + body, encoding="utf-8", newline="\n")
    print(f"  {path.relative_to(ROOT)}")


def read_csv(path: Path) -> list[dict[str, str]]:
    with path.open(encoding="utf-8-sig", newline="") as f:
        return list(csv.DictReader(f))


def pct(v: str | float, digits: int = 1) -> str:
    """A rate in [0,1] as a percentage. Empty source cell -> en dash."""
    if v == "" or v is None:
        return "--"
    return f"{float(v) * 100:.{digits}f}"


# ---------------------------------------------------------------- per-item regrading


def by_lang_passes(tag: str) -> dict[str, list[int]]:
    """Per-language 0/1 pass vector, regraded with the shipped grader."""
    out: dict[str, list[int]] = defaultdict(list)
    with (GEN / f"ag1-{tag}.jsonl").open(encoding="utf-8") as f:
        for line in f:
            r = json.loads(line)
            lang = r.get("lang", "en")
            out[lang].append(int(score_item(r.get("answer") or "", lang)["passed"]))
    return out


# A completion that stops without any sentence-final punctuation was cut off by the
# generation cap (MAX_NEW_SINGLE = 220 in run_local.py, HongBai-AG1 repo), not finished.
# The set spans the scripts in the suite, since `.` never appears in Hindi or Chinese.
_FINAL_PUNCT = set(".!?。！？؟۔।\"'’)`*")


def truncated(text: str) -> bool:
    t = clean_output(text or "").rstrip()
    return not t or t[-1] not in _FINAL_PUNCT


def by_lang_split(tag: str) -> tuple[dict[str, list[int]], dict[str, list[int]], dict[str, int]]:
    """Pass vectors for all items and for un-truncated items only, plus truncation counts.

    A truncated answer is scored as a failure by the harness -- correctly, since the text
    the model emitted does not contain the argument. But it is a failure of the token
    budget rather than of the model, so the paper reports both.
    """
    allp: dict[str, list[int]] = defaultdict(list)
    keep: dict[str, list[int]] = defaultdict(list)
    cut: dict[str, int] = defaultdict(int)
    with (GEN / f"ag1-{tag}.jsonl").open(encoding="utf-8") as f:
        for line in f:
            r = json.loads(line)
            lang = r.get("lang", "en")
            ans = r.get("answer") or ""
            p = int(score_item(ans, lang)["passed"])
            allp[lang].append(p)
            if truncated(ans):
                cut[lang] += 1
            else:
                keep[lang].append(p)
    return allp, keep, cut


def _macro(by_lang: dict[str, list[int]], codes) -> float | None:
    """Unweighted mean of per-language accuracies over `codes`."""
    accs = [sum(v) / len(v) for c in codes if (v := by_lang.get(c))]
    return sum(accs) / len(accs) if accs else None


def composite(by_lang: dict[str, list[int]]) -> float:
    """Macro-average within each language group, then blend. Mirrors score_suite."""

    def macro(codes):
        return _macro(by_lang, codes)

    core, ext = macro(CORE_LANGS), macro(EXTENDED_LANGS)
    if core is None:
        return ext
    if ext is None:
        return core
    return (1 - EXTENDED_WEIGHT) * core + EXTENDED_WEIGHT * ext


def bootstrap(by_lang: dict[str, list[int]]) -> tuple[float, float, float]:
    """Point estimate and percentile CI, resampling *within* each language group.

    Resampling the item pool as a whole would let language weights drift between
    replicates, and the composite is a macro-average over languages.
    """
    point = composite(by_lang)
    rng = random.Random(BOOT_SEED)
    reps = sorted(
        composite({lang: [rng.choice(v) for _ in v] for lang, v in by_lang.items()})
        for _ in range(BOOT_REPS)
    )
    return point * 100, reps[int(0.025 * BOOT_REPS)] * 100, reps[int(0.975 * BOOT_REPS) - 1] * 100


