    for i, (tag, label) in enumerate(reversed(MODELS)):
        pt, lo, hi = cis[tag]
        plain = label.replace(r"\textbf{", "").replace("}", "").replace(" (ours)", "")
        labels.append(f"{plain}")
        bars.append(f"({pt},{i}) += ({hi - pt},0) -= ({pt - lo},0)")
