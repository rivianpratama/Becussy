def tab_transcripts(tag: str = "v4-360-single") -> None:
    """Verbatim prompt/answer pairs, pulled from the graded run.

    Nothing is edited except `clean_output`, which strips the empty `<think></think>`
    block the chat template emits -- the same normalisation the grader applies. Selected
    to show the range: arithmetic, code, two adversarial constraints, and identity.
    """
    picks = ["ag1-008", "ag1-013", "ag1-031", "ag1-032", "ag1-034"]
    rows = {}
    with (GEN / f"ag1-{tag}.jsonl").open(encoding="utf-8") as f:
        for line in f:
            r = json.loads(line)
            if r["pid"] in picks:
                rows[r["pid"]] = r

    def _tex(s: str) -> str:
        for a, b in (
            ("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("$", r"\$"),
            ("#", r"\#"), ("_", r"\_"), ("{", r"\{"), ("}", r"\}"),
            ("~", r"\textasciitilde{}"), ("^", r"\textasciicircum{}"),
            ("–", "--"), ("—", "---"), ("’", "'"), ("‘", "`"), ("“", "``"), ("”", "''"),
        ):
            s = s.replace(a, b)
        return s

    def esc(s: str) -> str:
        """Verbatim model text into LaTeX.

        Fenced code blocks become inline `\\texttt` rather than being flattened into the
        surrounding prose, which would silently misrepresent what the model emitted. The
        replacement character comes from the run log's console encoding, not the model.
        """
        s = s.replace("�", "--")
        parts, out = re.split(r"```[a-z]*\n?(.*?)```", s, flags=re.S), []
        for i, part in enumerate(parts):
            if i % 2:  # inside a fence
                out.append(r"\texttt{" + _tex(" ".join(part.split())) + "}")
            else:
                out.append(_tex(" ".join(part.split())))
        return " ".join(x for x in out if x).strip()

    body = []
    for pid in picks:
        r = rows[pid]
        ans = clean_output(r.get("answer") or "")
        note = r" \emph{(cut off by the 220-token cap.)}" if truncated(ans) else ""
        body += [
            r"\begin{quote}\small",
            rf"\textbf{{Q}} ({pid}, \texttt{{{r['category']}}}, \texttt{{{r['lang']}}}): "
            rf"{esc(r['prompt'])}",
            r"",
            rf"\textbf{{A}}: {esc(ans)}{note}",
            r"\end{quote}",
            "",
        ]
    write(TABLES / "transcripts.tex", f"eval/generations/ag1-{tag}.jsonl (verbatim)", "\n".join(body))


